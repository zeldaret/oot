/*
This function takes as input a codepoint and returns the corresponding offset into the kanji textures segment.
It only accepts codepoints starting from 0x8140.

Equivalent C code:

extern s16 low_codepoints_lookup_table[];
s32 KanjiTex_CodepointToOffset(s32 codepoint) {
    s32 i;

    if (codepoint < 0x8800) {
        i = (codepoint & 0xFF) - 0x40;
        if (i >= 0x40) {
            i -= 1;
        }
        i += ((codepoint >> 8) - 0x81) * 0xBC;
        return low_codepoints_lookup_table[i] * FONT_CHAR_TEX_SIZE;
    } else {
        i = (codepoint & 0xFF) - 0x40;
        if (i >= 0x40) {
            i -= 1;
        }
        i += 0x30A;
        i += ((codepoint >> 8) - 0x88) * 0xBC;
        return i * FONT_CHAR_TEX_SIZE;
    }
}
*/

LEAF(KanjiTex_CodepointToOffset)
    li      a2, 188
    blt     a0, 0x8800, low_codepoint
    srl     a1, a0, 8
    addi    a1, a1, -0x88
    andi    a3, a0, 0xFF
    addi    a3, a3, -0x40
    mul     a2, a2, a1
    blt     a3, 0x40, 1f
    addi    a3, a3, -1
1:
    mflo    a2  /* Unncessary mflo: the pseudo-op `mul` already performs mflo */
    addi    a3, a3, 0x030A
    add     a3, a3, a2
    sll     v0, a3, 7
    jr      ra

low_codepoint:
    srl     a1, a0, 8
    addi    a1, a1, -0x81
    andi    a3, a0, 0xFF
    addi    a3, a3, -0x40
    mul     a2, a2, a1
    blt     a3, 0x40, 1f
    addi    a3, a3, -1
1:
    mflo    a2  /* Unncessary mflo: the pseudo-op `mul` already performs mflo */
    add     a3, a3, a2
    sll     a3, a3, 1
    la      a2, low_codepoints_lookup_table
    add     a3, a3, a2
    lh      a2, (a3)
    sll     v0, a2, 7
    jr      ra
END(KanjiTex_CodepointToOffset)

